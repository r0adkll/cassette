#!/usr/bin/env python3
"""Generates Compose ImageVectors for the Lucide icons Cassette uses.

Usage: scripts/generate-lucide-icons.py
Edit ICONS to add one, then re-run. Lucide is ISC licensed (thirdparty/licenses/Lucide-LICENSE.txt).
"""
import re
import urllib.request
from pathlib import Path

VERSION = "0.460.0"
ICONS = [
    "activity", "arrow-left", "battery-low", "battery-medium", "battery-warning", "bell", "bell-ring",
    "bike", "bluetooth", "bluetooth-searching", "check", "chevron-down", "chevron-left", "chevron-right", "circle-check",
    "circle-help", "cpu", "download", "file-text", "history", "image-plus", "info", "layout-grid", "mountain",
    "panel-top", "pin", "radio", "shield",
    "refresh-cw", "route", "scan-line", "settings", "share-2", "signal", "x",
]
# Cassette's own combinations of Lucide parts, in Lucide's grid and stroke: name -> (base icon,
# extra SVG elements). bike-plus is "Add bike": Lucide's bike with a + in its empty top-left.
COMBINED = {
    "bike-plus": ("bike", ['<path d="M5 2v6" />', '<path d="M2 5h6" />']),
}
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "common/compose/src/commonMain/kotlin/com/r0adkll/cassette/common/compose/icons/LucideIcons.kt"

# Android vector drawables for surfaces that can't use ImageVector (Quick Settings tile, Wear tile and
# complications), as
# res/drawable/lucide_<name>.xml in each module.
ANDROID_ICONS = {
    ROOT / "surfaces/tile/src/main/res/drawable": [
        "circle-check", "battery-low", "battery-warning", "history", "circle-help", "refresh-cw", "bike",
    ],
    ROOT / "app/wear/src/main/res/drawable": [
        "circle-check", "battery-low", "battery-warning", "history", "circle-help", "refresh-cw", "bike",
    ],
}


def attrs(tag):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', tag))


def to_path(tag):
    name = re.match(r"<(\w+)", tag).group(1)
    a = attrs(tag)
    f = lambda k, d="0": float(a.get(k, d))
    if name == "path":
        return a["d"]
    if name == "circle":
        cx, cy, r = f("cx"), f("cy"), f("r")
        return f"M{cx - r} {cy}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 {-2 * r} 0Z"
    if name == "ellipse":
        cx, cy, rx, ry = f("cx"), f("cy"), f("rx"), f("ry")
        return f"M{cx - rx} {cy}a{rx} {ry} 0 1 0 {2 * rx} 0a{rx} {ry} 0 1 0 {-2 * rx} 0Z"
    if name == "line":
        return f"M{f('x1')} {f('y1')}L{f('x2')} {f('y2')}"
    if name in ("polyline", "polygon"):
        pts = a["points"].replace(",", " ").split()
        d = "M" + " L".join(f"{pts[i]} {pts[i + 1]}" for i in range(0, len(pts), 2))
        return d + ("Z" if name == "polygon" else "")
    if name == "rect":
        x, y, w, h = f("x"), f("y"), f("width"), f("height")
        rx = float(a.get("rx", a.get("ry", 0)))
        ry = float(a.get("ry", rx))
        if rx == 0:
            return f"M{x} {y}h{w}v{h}h{-w}Z"
        return (f"M{x + rx} {y}h{w - 2 * rx}a{rx} {ry} 0 0 1 {rx} {ry}v{h - 2 * ry}a{rx} {ry} 0 0 1 {-rx} {ry}"
                f"h{-(w - 2 * rx)}a{rx} {ry} 0 0 1 {-rx} {-ry}v{-(h - 2 * ry)}a{rx} {ry} 0 0 1 {rx} {-ry}Z")
    raise ValueError(name)


def pascal(name):
    # share-2 is Lucide's current share glyph; the suffix is a revision, not part of the name.
    return "".join(p.capitalize() for p in re.sub(r"-2$", "", name).split("-"))


def main():
    props = []
    for icon in ICONS + list(COMBINED):
        base, extra = COMBINED.get(icon, (icon, []))
        url = f"https://unpkg.com/lucide-static@{VERSION}/icons/{base}.svg"
        svg = urllib.request.urlopen(url).read().decode()
        tags = re.findall(r"<(?:path|circle|rect|line|polyline|polygon|ellipse)\b[^>]*/>", svg) + extra
        paths = "\n".join(f'            stroke("{to_path(t)}")' for t in tags)
        doc = f"Cassette's `{icon}`: Lucide `{base}` plus a +." if icon in COMBINED else f"Lucide `{icon}`."
        props.append(f"""    /** {doc} */
    val {pascal(icon)}: ImageVector by lazy {{
        lucide("{pascal(icon)}") {{
{paths}
        }}
    }}""")
    body = "\n\n".join(props)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(f"""// Generated by scripts/generate-lucide-icons.py from lucide-static {VERSION}. Do not edit.
// Lucide is ISC licensed: thirdparty/licenses/Lucide-LICENSE.txt
package com.r0adkll.cassette.common.compose.icons

import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp
import androidx.compose.ui.graphics.Color

object LucideIcons {{
{body}
}}

private class LucideBuilder(val builder: ImageVector.Builder) {{
    fun stroke(pathData: String) {{
        builder.addPath(
            pathData = addPathNodes(pathData),
            fill = null,
            stroke = SolidColor(Color.Black),
            strokeLineWidth = 2f,
            strokeLineCap = StrokeCap.Round,
            strokeLineJoin = StrokeJoin.Round,
        )
    }}
}}

private fun lucide(name: String, block: LucideBuilder.() -> Unit): ImageVector =
    ImageVector.Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 24f,
            viewportHeight = 24f,
        )
        .also {{ LucideBuilder(it).block() }}
        .build()
""")
    print(f"Wrote {len(ICONS) + len(COMBINED)} icons to {OUT}")

    for directory, names in ANDROID_ICONS.items():
        directory.mkdir(parents=True, exist_ok=True)
        for icon in names:
            url = f"https://unpkg.com/lucide-static@{VERSION}/icons/{icon}.svg"
            svg = urllib.request.urlopen(url).read().decode()
            tags = re.findall(r"<(?:path|circle|rect|line|polyline|polygon|ellipse)\b[^>]*/>", svg)
            paths = "\n".join(
                f'''    <path
        android:pathData="{to_path(t)}"
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="2"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />'''
                for t in tags
            )
            (directory / f"lucide_{icon.replace('-', '_')}.xml").write_text(
                f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-lucide-icons.py from lucide-static {VERSION} (ISC). Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
{paths}
</vector>
'''
            )
        print(f"Wrote {len(names)} Android vectors to {directory}")


main()
